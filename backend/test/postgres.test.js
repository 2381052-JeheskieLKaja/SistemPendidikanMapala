const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const bcrypt = require('bcryptjs');

const dbDir = path.resolve(__dirname, '../db');
const srcDir = path.resolve(__dirname, '../src');

const schemaSql = fs.readFileSync(path.join(dbDir, 'schema.sql'), 'utf8');
const seedSql = fs.readFileSync(path.join(dbDir, 'seed.sql'), 'utf8');

const EXPECTED_TABLES = [
  'users',
  'anggota',
  'program_pendidikan',
  'kurikulum',
  'materi',
  'jadwal',
  'peserta_pendidikan',
  'absensi',
  'progres_materi',
  'notifikasi',
  'evaluasi',
];

const EXPECTED_ENUMS = [
  'user_role',
  'user_status',
  'anggota_status',
  'program_jenis',
  'kurikulum_status',
  'peserta_status',
  'absensi_status',
  'progres_status',
];

function collectJsFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectJsFiles(full));
    } else if (entry.name.endsWith('.js')) {
      files.push(full);
    }
  }
  return files;
}

test('PostgreSQL schema.sql mendefinisikan semua ENUM, 11 tabel, identity key, relasi FK sesuai urutan, dan index', () => {
  for (const enumName of EXPECTED_ENUMS) {
    assert.match(
      schemaSql,
      new RegExp(`CREATE\\s+TYPE\\s+${enumName}\\s+AS\\s+ENUM\\s*\\(`, 'i'),
      `ENUM ${enumName} harus didefinisikan di schema.sql`
    );
  }

  const createdOrder = [];
  const createTableRe = /CREATE\s+TABLE\s+([a-z_]+)\s*\(([\s\S]*?)\n\);/gi;
  let match;
  while ((match = createTableRe.exec(schemaSql)) !== null) {
    const [, tableName, body] = match;
    createdOrder.push(tableName);

    assert.match(
      body,
      /INTEGER\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s+PRIMARY\s+KEY/i,
      `Tabel ${tableName} harus memakai GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`
    );

    const fkRe = /REFERENCES\s+([a-z_]+)\s*\(/gi;
    let fkMatch;
    while ((fkMatch = fkRe.exec(body)) !== null) {
      const refTable = fkMatch[1];
      assert.ok(
        createdOrder.includes(refTable),
        `Tabel ${tableName} mereferensikan ${refTable} sebelum ${refTable} dibuat`
      );
    }
  }

  assert.deepEqual(createdOrder, EXPECTED_TABLES);

  // Verifikasi aturan ON DELETE CASCADE khusus progres_materi & notifikasi
  assert.match(schemaSql, /CONSTRAINT\s+fk_progres_materi\s+FOREIGN\s+KEY\s*\(id_materi\)\s+REFERENCES\s+materi\(id_materi\)\s+ON\s+DELETE\s+CASCADE/i);
  assert.match(schemaSql, /CONSTRAINT\s+fk_notifikasi_materi\s+FOREIGN\s+KEY\s*\(id_materi\)\s+REFERENCES\s+materi\(id_materi\)\s+ON\s+DELETE\s+CASCADE/i);

  // Verifikasi tidak ada sintaks MySQL yang tersisa
  assert.doesNotMatch(schemaSql, /AUTO_INCREMENT|ENGINE\s*=|CHARSET\s*=|FOREIGN_KEY_CHECKS|TINYINT\s*\(/i);
});

test('PostgreSQL seed.sql idempotent, memelihara seluruh data awal & sequence sync untuk 11 tabel', async () => {
  assert.match(seedSql, /^[\s\S]*\bBEGIN;\s*/m);
  assert.match(seedSql, /\bCOMMIT;\s*$/m);

  // Pastikan seluruh 11 tabel diisi dengan ON CONFLICT DO NOTHING & sequence di-reset
  for (const tableName of EXPECTED_TABLES) {
    assert.match(
      seedSql,
      new RegExp(`INSERT\\s+INTO\\s+${tableName}\\b[\\s\\S]*?ON\\s+CONFLICT\\b[\\s\\S]*?DO\\s+NOTHING`, 'i'),
      `INSERT untuk ${tableName} harus idempotent (ON CONFLICT ... DO NOTHING)`
    );
    assert.match(
      seedSql,
      new RegExp(`SELECT\\s+setval\\(pg_get_serial_sequence\\('${tableName}'`, 'i'),
      `Sequence untuk ${tableName} harus disinkronkan via pg_get_serial_sequence`
    );
  }

  // Pastikan email akun admin & anggota seed utuh dan hash bcrypt cocok dengan 'password123'
  assert.match(seedSql, /'admin@mapala\.test'/);
  assert.match(seedSql, /'pengurus@mapala\.test'/);
  assert.match(seedSql, /'budi@mapala\.test'/);
  assert.match(seedSql, /'sari@mapala\.test'/);
  assert.match(seedSql, /'andi@mapala\.test'/);

  const hashMatch = seedSql.match(/'(\$2[aby]\$\d{2}\$[^']+)'/);
  assert.ok(hashMatch, 'Hash bcrypt akun seed harus ada di seed.sql');
  const validPassword = await bcrypt.compare('password123', hashMatch[1]);
  assert.equal(validPassword, true, 'Hash password di seed.sql harus cocok dengan password123');

  // Boolean PostgreSQL & tanpa variabel MySQL
  assert.match(seedSql, /,\s*TRUE,\s*'2026-09-05/);
  assert.match(seedSql, /,\s*FALSE,\s*'2026-09-20/);
  assert.doesNotMatch(seedSql, /\bSET\s+@|ON\s+DUPLICATE\s+KEY/i);
});

test('Kode backend bebas sintaks MySQL & memakai driver/error code PostgreSQL', () => {
  const jsFiles = [
    ...collectJsFiles(srcDir),
    path.join(dbDir, 'reset.js'),
  ];

  for (const filePath of jsFiles) {
    const content = fs.readFileSync(filePath, 'utf8');
    const rel = path.relative(path.resolve(__dirname, '..'), filePath);
    assert.doesNotMatch(
      content,
      /mysql2|CURDATE\s*\(|ON\s+DUPLICATE\s+KEY|ER_DUP_ENTRY|ER_ROW_IS_REFERENCED|ER_NO_REFERENCED|DROP\s+CHECK|\.insertId\b/,
      `File ${rel} masih mengandung sintaks khusus MySQL`
    );
  }

  const pkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../package.json'), 'utf8'));
  assert.ok(pkg.dependencies.pg, 'backend/package.json harus mencantumkan dependency pg');
  assert.equal(pkg.dependencies.mysql2, undefined, 'backend/package.json tidak boleh mencantumkan mysql2');

  const envConfig = require('../src/config/env');
  assert.equal(envConfig.db.port, Number(process.env.DB_PORT || process.env.PGPORT || 5432));
});

test('Konfigurasi Vercel (vercel.json & api/index.js) dan koneksi Neon (DATABASE_URL + SSL) valid', () => {
  const rootDir = path.resolve(__dirname, '../..');
  const vercel = JSON.parse(fs.readFileSync(path.join(rootDir, 'vercel.json'), 'utf8'));

  assert.match(vercel.buildCommand, /npm --prefix backend run db:reset/);
  assert.match(vercel.buildCommand, /npm --prefix frontend run build/);
  assert.equal(vercel.outputDirectory, 'frontend/dist');
  assert.ok(vercel.functions?.['api/index.js']?.includeFiles?.includes('backend/'));
  assert.ok(vercel.rewrites.some((r) => r.source === '/api/(.*)' && r.destination === '/api/index.js'));
  assert.ok(vercel.rewrites.some((r) => r.destination === '/index.html'));

  const apiHandler = require(path.join(rootDir, 'api/index.js'));
  assert.equal(typeof apiHandler, 'function');

  // Simulasikan environment non-test dengan Neon DATABASE_URL
  const savedEnv = {
    NODE_ENV: process.env.NODE_ENV,
    DATABASE_URL: process.env.DATABASE_URL,
    DB_SSL: process.env.DB_SSL,
    VERCEL: process.env.VERCEL,
  };
  const envPath = require.resolve('../src/config/env');
  delete require.cache[envPath];
  try {
    process.env.NODE_ENV = 'production';
    process.env.DATABASE_URL = 'postgresql://neondb_owner:secret@ep-demo-123.ap-southeast-1.aws.neon.tech/neondb?sslmode=require';
    delete process.env.DB_SSL;
    process.env.VERCEL = '1';

    const prodEnv = require('../src/config/env');
    assert.equal(prodEnv.db.connectionString, process.env.DATABASE_URL);
    assert.deepEqual(prodEnv.db.ssl, { rejectUnauthorized: false });
    assert.ok(prodEnv.uploadDir.includes('mapala-uploads'));
  } finally {
    delete require.cache[envPath];
    for (const [k, v] of Object.entries(savedEnv)) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
    require('../src/config/env');
  }
});
