-- Skema database PostgreSQL Sistem Pendidikan MAPALA Eden Club UNAI (implementation.md §11).
-- 11 tabel. Urutan pembuatan mengikuti dependensi FK.
-- ON DELETE: RESTRICT untuk semua FK, kecuali progres_materi.id_materi dan notifikasi.id_materi (CASCADE).

DROP TABLE IF EXISTS
  evaluasi,
  notifikasi,
  progres_materi,
  absensi,
  peserta_pendidikan,
  jadwal,
  materi,
  kurikulum,
  program_pendidikan,
  anggota,
  users
CASCADE;

DROP TYPE IF EXISTS
  progres_status,
  absensi_status,
  peserta_status,
  kurikulum_status,
  program_jenis,
  anggota_status,
  user_status,
  user_role
CASCADE;

CREATE TYPE user_role AS ENUM ('admin', 'pengurus', 'siswa');
CREATE TYPE user_status AS ENUM ('aktif', 'nonaktif');
CREATE TYPE anggota_status AS ENUM (
  'calon_siswa',
  'siswa',
  'calon_anggota',
  'anggota',
  'ppa',
  'dp',
  'pemburu_tua'
);
CREATE TYPE program_jenis AS ENUM ('rutin', 'tambahan');
CREATE TYPE kurikulum_status AS ENUM ('draft', 'diresmikan');
CREATE TYPE peserta_status AS ENUM ('aktif', 'selesai');
CREATE TYPE absensi_status AS ENUM ('hadir', 'izin', 'sakit', 'alpa');
CREATE TYPE progres_status AS ENUM ('belum_diakses', 'sudah_diakses');

CREATE TABLE users (
  id_user  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama     VARCHAR(100) NOT NULL,
  email    VARCHAR(100) NOT NULL,
  password VARCHAR(255) NOT NULL,
  no_hp    VARCHAR(20) NULL,
  role     user_role NOT NULL,
  status   user_status NOT NULL DEFAULT 'aktif',
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE anggota (
  id_anggota         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user            INTEGER NOT NULL,
  nim                VARCHAR(20) NULL,
  jurusan            VARCHAR(100) NULL,
  angkatan           VARCHAR(10) NULL,
  kontak             VARCHAR(50) NULL,
  status_keanggotaan anggota_status NOT NULL DEFAULT 'calon_siswa',
  CONSTRAINT uq_anggota_user UNIQUE (id_user),
  CONSTRAINT uq_anggota_nim UNIQUE (nim),
  CONSTRAINT fk_anggota_user FOREIGN KEY (id_user) REFERENCES users(id_user) ON DELETE RESTRICT
);

CREATE TABLE program_pendidikan (
  id_program      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_program    VARCHAR(150) NOT NULL,
  jenis           program_jenis NOT NULL,
  deskripsi       TEXT NULL,
  tanggal_mulai   DATE NULL,
  tanggal_selesai DATE NULL
);

CREATE TABLE kurikulum (
  id_kurikulum INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_program   INTEGER NOT NULL,
  tahun        VARCHAR(10) NOT NULL,
  deskripsi    TEXT NULL,
  status       kurikulum_status NOT NULL DEFAULT 'draft',
  CONSTRAINT fk_kurikulum_program FOREIGN KEY (id_program) REFERENCES program_pendidikan(id_program) ON DELETE RESTRICT
);

CREATE TABLE materi (
  id_materi      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_program     INTEGER NOT NULL,
  judul          VARCHAR(150) NOT NULL,
  kategori       VARCHAR(100) NOT NULL,
  deskripsi      TEXT NULL,
  file_path      VARCHAR(255) NULL,
  tanggal_upload TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_materi_program FOREIGN KEY (id_program) REFERENCES program_pendidikan(id_program) ON DELETE RESTRICT
);

CREATE TABLE jadwal (
  id_jadwal  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_program INTEGER NOT NULL,
  tanggal    DATE NOT NULL,
  waktu      TIME NOT NULL,
  lokasi     VARCHAR(150) NOT NULL,
  kegiatan   VARCHAR(150) NOT NULL,
  CONSTRAINT fk_jadwal_program FOREIGN KEY (id_program) REFERENCES program_pendidikan(id_program) ON DELETE RESTRICT
);

CREATE TABLE peserta_pendidikan (
  id_peserta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_anggota     INTEGER NOT NULL,
  id_program     INTEGER NOT NULL,
  tanggal_daftar DATE NOT NULL,
  status         peserta_status NOT NULL DEFAULT 'aktif',
  CONSTRAINT uq_peserta_anggota_program UNIQUE (id_anggota, id_program),
  CONSTRAINT fk_peserta_anggota FOREIGN KEY (id_anggota) REFERENCES anggota(id_anggota) ON DELETE RESTRICT,
  CONSTRAINT fk_peserta_program FOREIGN KEY (id_program) REFERENCES program_pendidikan(id_program) ON DELETE RESTRICT
);

CREATE TABLE absensi (
  id_absensi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peserta INTEGER NOT NULL,
  id_jadwal  INTEGER NOT NULL,
  status     absensi_status NOT NULL,
  keterangan TEXT NULL,
  CONSTRAINT uq_absensi_peserta_jadwal UNIQUE (id_peserta, id_jadwal),
  CONSTRAINT fk_absensi_peserta FOREIGN KEY (id_peserta) REFERENCES peserta_pendidikan(id_peserta) ON DELETE RESTRICT,
  CONSTRAINT fk_absensi_jadwal FOREIGN KEY (id_jadwal) REFERENCES jadwal(id_jadwal) ON DELETE RESTRICT
);

CREATE TABLE progres_materi (
  id_progres    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peserta    INTEGER NOT NULL,
  id_materi     INTEGER NOT NULL,
  status        progres_status NOT NULL DEFAULT 'belum_diakses',
  tanggal_akses TIMESTAMP NULL,
  CONSTRAINT uq_progres_peserta_materi UNIQUE (id_peserta, id_materi),
  CONSTRAINT fk_progres_peserta FOREIGN KEY (id_peserta) REFERENCES peserta_pendidikan(id_peserta) ON DELETE RESTRICT,
  CONSTRAINT fk_progres_materi FOREIGN KEY (id_materi) REFERENCES materi(id_materi) ON DELETE CASCADE
);

CREATE TABLE notifikasi (
  id_notifikasi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user       INTEGER NOT NULL,
  id_materi     INTEGER NOT NULL,
  pesan         VARCHAR(255) NOT NULL,
  status_baca   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notifikasi_user FOREIGN KEY (id_user) REFERENCES users(id_user) ON DELETE RESTRICT,
  CONSTRAINT fk_notifikasi_materi FOREIGN KEY (id_materi) REFERENCES materi(id_materi) ON DELETE CASCADE
);

CREATE TABLE evaluasi (
  id_evaluasi      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peserta       INTEGER NOT NULL,
  id_jadwal        INTEGER NOT NULL,
  id_pencatat      INTEGER NOT NULL,
  hasil_penilaian  TEXT NOT NULL,
  catatan          TEXT NULL,
  tanggal_evaluasi DATE NOT NULL,
  CONSTRAINT uq_evaluasi_peserta_jadwal UNIQUE (id_peserta, id_jadwal),
  CONSTRAINT fk_evaluasi_peserta FOREIGN KEY (id_peserta) REFERENCES peserta_pendidikan(id_peserta) ON DELETE RESTRICT,
  CONSTRAINT fk_evaluasi_jadwal FOREIGN KEY (id_jadwal) REFERENCES jadwal(id_jadwal) ON DELETE RESTRICT,
  CONSTRAINT fk_evaluasi_pencatat FOREIGN KEY (id_pencatat) REFERENCES users(id_user) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_kurikulum_program ON kurikulum (id_program);
CREATE INDEX IF NOT EXISTS idx_materi_program ON materi (id_program);
CREATE INDEX IF NOT EXISTS idx_jadwal_program_tanggal ON jadwal (id_program, tanggal, waktu);
CREATE INDEX IF NOT EXISTS idx_peserta_program ON peserta_pendidikan (id_program);
CREATE INDEX IF NOT EXISTS idx_absensi_jadwal ON absensi (id_jadwal);
CREATE INDEX IF NOT EXISTS idx_progres_materi_materi ON progres_materi (id_materi);
CREATE INDEX IF NOT EXISTS idx_notifikasi_user_baca ON notifikasi (id_user, status_baca, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_evaluasi_jadwal ON evaluasi (id_jadwal);
CREATE INDEX IF NOT EXISTS idx_evaluasi_pencatat ON evaluasi (id_pencatat);
